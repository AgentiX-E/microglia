/**
 * The gate coverage matrix, generated rather than described.
 *
 * `tau2-gates.ts` holds two tables and a promise: thirteen gates the τ² record type can feed and
 * twenty-six it cannot. Both numbers are quoted in the audit, the white paper and three
 * registrations, and prose that quotes a table is prose that drifts from it — this repository has
 * paid for that lesson twice, once in `gates.ts` ("9 supplyable, 30 arm-indexed" against a table
 * that said 13 and 26) and once in a release note.
 *
 * So the document is a projection of the tables: `docs/GATE-COVERAGE-MATRIX.md` is written by this
 * program, and a reader who wants to know what the lane can certify reads the same data the audit
 * reads. The test beside it fails when the file on disk is not what the tables produce.
 *
 * The BIRD column is a measurement, not a capability: it lists the gates the last published BIRD
 * artefact actually carried, which is why it is read from the artefact rather than from the type.
 * A lane's type being able to supply a field is not evidence that a run supplied it.
 */

import { GATE_ORDER } from '@agentix-e/microglia-protocol';
import { TAU2_GATE_INDEX, type Tau2Field } from './tau2-gates.js';

export type GateRow = {
  readonly id: string;
  /** The protocol field the gate reads, for a gate the τ² record can feed. */
  readonly field?: Tau2Field;
  /** Which of the two tables the gate appears in. */
  readonly lane: 'supplyable' | 'arm-indexed';
  /** What the gate needs, when it needs an arm this lane never ran. */
  readonly needs: string;
  /** Whether the BIRD artefact this document was rendered against carried the gate. */
  readonly bird: boolean;
};

/**
 * One row per gate in publication order.
 *
 * The order is `GATE_ORDER` rather than the tables' order, because the matrix is read beside a
 * report: a reader looking for `V44` should find it where the artefact prints it.
 */
export function gateRows(
  birdGateIds: readonly string[],
  // Injectable so the test can hold the guard rather than trust it: the one failure this function
  // must not have is silently omitting a gate the protocol publishes, and that path is unreachable
  // while the shipped tables happen to be complete.
  source: {
    readonly order?: readonly string[];
    readonly index?: typeof TAU2_GATE_INDEX;
  } = {},
): readonly GateRow[] {
  const order = source.order ?? GATE_ORDER;
  const index = source.index ?? TAU2_GATE_INDEX;
  const bird = new Set(birdGateIds);
  const byId = new Map<string, GateRow>();
  for (const entry of index.supplyable) {
    byId.set(entry.id, {
      id: entry.id,
      field: entry.field,
      lane: 'supplyable',
      needs: 'the field exists in this lane’s record type',
      bird: bird.has(entry.id),
    });
  }
  for (const entry of index.armIndexed) {
    byId.set(entry.id, {
      id: entry.id,
      lane: 'arm-indexed',
      needs: entry.needs,
      bird: bird.has(entry.id),
    });
  }
  return order.map((id) => {
    const row = byId.get(id);
    // A gate in neither table is a gate no audit would account for, and a matrix that silently
    // omitted it would be the drift this file exists to prevent. Throwing here makes the omission
    // a failed build rather than a missing line.
    if (row === undefined) throw new Error(`gate ${id} is in neither table`);
    return row;
  });
}

export function renderMatrix(rows: readonly GateRow[], birdLabel: string): string {
  const supplyable = rows.filter((row) => row.lane === 'supplyable').length;
  const armIndexed = rows.filter((row) => row.lane === 'arm-indexed').length;
  const carried = rows.filter((row) => row.bird).length;
  const lines = [
    '# Gate coverage matrix',
    '',
    '> Generated by `packages/eval/src/bin/gate-matrix.ts`. Do not edit by hand: the test beside it',
    '> fails when this file is not what the two tables produce.',
    '',
    `Every published number this project reports is certified by one of ${String(rows.length)} gates. The`,
    'table says, for each, whether the τ² lane can feed it and whether the last published BIRD',
    `artefact (${birdLabel}) carried it.`,
    '',
    '| | count |',
    '| --- | --- |',
    `| gates in the protocol | ${String(rows.length)} |`,
    `| τ² can supply | ${String(supplyable)} |`,
    `| τ² needs an arm it never ran | ${String(armIndexed)} |`,
    `| BIRD carried in this artefact | ${String(carried)} |`,
    '',
    'A supplied gate is not a passing gate, and it is not a meaningful one either: `V6` and `V7`',
    'fire on an empty control list and certify nothing. They are counted as supplyable because they',
    'do run, and the count of gates that actually decide something is smaller than either column.',
    '',
    '| gate | τ² | reads, or needs | BIRD |',
    '| --- | --- | --- | --- |',
  ];
  for (const row of rows) {
    const what = row.field === undefined ? row.needs : `\`${row.field}\``;
    lines.push(
      `| \`${row.id}\` | ${row.lane === 'supplyable' ? 'supplyable' : 'arm-indexed'} | ${what} | ${row.bird ? 'yes' : '—'} |`,
    );
  }
  lines.push('');
  return lines.join('\n');
}
