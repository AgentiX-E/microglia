import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { mergeOperations, parseOperations, type Entry, type Identity, type Operation } from '../rule-bank.js';

/**
 * The shared contract, read from the file the Python lane's own test reads.
 *
 * `eval/drivers/alfworld/distill.py` is the second implementation of this arithmetic, because the ALFWorld
 * lane runs where `textworld` is installed and `node` is not guaranteed. Two implementations of one
 * algorithm are a drift hazard, and the only arrangement in which a drift is a red build on both sides
 * rather than a silent divergence is a contract both test suites read.
 *
 * The file is not generated from either implementation on purpose: a fixture generated by the code it
 * checks agrees with that code by construction, and the cases here were written from
 * `agent/expel.py@LeapLabTHU/ExpeL` (`parse_rules`, `update_rules`) and then checked against both ports.
 */

type Case = {
  readonly name: string;
  readonly identity: Identity;
  readonly cap: number | null;
  readonly bank: readonly Entry[];
  readonly reply: string;
  readonly parsed: readonly Operation[];
  readonly expect: {
    readonly bank?: readonly Entry[];
    readonly bank_entry_text?: string;
    readonly bank_entry_votes?: number;
    readonly applied: number;
    readonly rejected: number;
    readonly culled: number;
    readonly peak: number;
  };
};

const HERE = dirname(fileURLToPath(import.meta.url));
const CONTRACT = join(HERE, '..', '..', '..', '..', 'eval', 'drivers', 'alfworld', 'rule-op-vectors.json');
const VECTORS = JSON.parse(readFileSync(CONTRACT, 'utf8')) as {
  readonly note: string;
  readonly source: string;
  readonly cases: readonly Case[];
};

describe('the rule arithmetic contract', () => {
  it('is the file the Python lane reads, with cases in it', () => {
    expect(VECTORS.note).toContain('test_distill.py');
    expect(VECTORS.source).toContain('LeapLabTHU/ExpeL');
    expect(VECTORS.cases.length).toBeGreaterThanOrEqual(18);
  });

  for (const testCase of VECTORS.cases) {
    it(`parses and merges: ${testCase.name}`, () => {
      expect(parseOperations(testCase.reply)).toEqual(testCase.parsed);
      const report = mergeOperations(testCase.bank, parseOperations(testCase.reply), {
        identity: testCase.identity,
        cap: testCase.cap,
      });
      expect(report.applied).toBe(testCase.expect.applied);
      expect(report.rejected).toBe(testCase.expect.rejected);
      expect(report.culled).toBe(testCase.expect.culled);
      expect(report.peak).toBe(testCase.expect.peak);
      if (testCase.expect.bank !== undefined) {
        expect(report.bank).toEqual(testCase.expect.bank);
        return;
      }
      // One case is 25 entries long and asserts the arithmetic rather than the whole list: a removal past
      // the cap's margin costs three votes. The entry is found by text because the bank is sorted by votes
      // after the merge, so an index would assert the sort rather than the penalty.
      const entry = report.bank.find((item) => item.text === testCase.expect.bank_entry_text);
      expect(entry?.votes).toBe(testCase.expect.bank_entry_votes);
    });
  }
});
